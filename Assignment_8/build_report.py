"""Build the full PS8 report (questions (a)-(g)) as pset8_xw564_esw63_xg325.pdf.

Usage:  python build_report.py

Questions (d)-(e) live in a standalone document, PS8_Questions_d_e.tex. This script copies
its body (without preamble or title) into partDE.tex, demoting its headings one level so
they sit under the report's section for (d)-(e), then runs pdflatex twice.
Edit PS8_Questions_d_e.tex, not partDE.tex, which is regenerated every run.
"""
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
MAIN = "pset8_xw564_esw63_xg325"

src = (HERE / "PS8_Questions_d_e.tex").read_text()
body = src.split(r"\begin{document}", 1)[1].split(r"\end{document}", 1)[0]
body = re.sub(r"\\begin\{center\}.*?\\end\{center\}", "", body, count=1, flags=re.S)  # drop title block
body = body.replace(r"\subsection*{", r"\subsubsection*{").replace(r"\section*{", r"\subsection*{")
(HERE / "partDE.tex").write_text(
    "% GENERATED by build_report.py from PS8_Questions_d_e.tex -- do not edit by hand.\n" + body.strip() + "\n")

for _ in range(2):
    subprocess.run(["pdflatex", "-interaction=nonstopmode", f"{MAIN}.tex"], cwd=HERE,
                   stdout=subprocess.DEVNULL, check=False)
log = (HERE / f"{MAIN}.log").read_text(errors="ignore")
problems = [l for l in log.splitlines() if l.startswith("!") or "undefined" in l or "Overfull" in l]
print("\n".join(problems) or "no errors or warnings")
print(re.search(r"Output written.*", log).group(0))
for ext in ("aux", "log", "out"):
    (HERE / f"{MAIN}.{ext}").unlink(missing_ok=True)
